"""Builds the live app (index.html + app.js at the site root) from the demo screens in central/
plus the Supabase data layer in src/live.js. Run: python3 tools/build-live.py"""
import re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
js = (root / 'central/app.js').read_text(encoding='utf-8')
html = (root / 'central/index.html').read_text(encoding='utf-8')

def rep(old, new, count=1):
    global js
    n = js.count(old)
    if n != count: sys.exit(f'build-live: expected {count}x, found {n}x: {old[:80]!r}')
    js = js.replace(old, new)

# no sample data or browser storage in the live app
a = js.index('function seed('); b = js.index('/* ============================================================ state */')
js = js[:a] + js[b:]
js = re.sub(r"const KEY = 'crewdesk-central-demo-v2';\n.*?\nfunction save\(\)[^\n]*\n", 'let S;\n', js, count=1, flags=re.S)
rep("const DEMO_URL = 'https://crewdesk-production.vercel.app/central/';", "const DEMO_URL = location.origin + '/';")
rep("const HOSTED = /vercel\\.app$|^localhost$|^127\\./.test(location.hostname) || location.protocol === 'file:';", "const HOSTED = true;")
# readiness comes from the database, which can see fields this person may not
js = re.sub(r"const profileDone = u => [^\n]*\n", "const profileDone = u => !!u?.ready?.profile;\n", js, count=1)
js = re.sub(r"const docsDone = u => [^\n]*\n", "const docsDone = u => !!u?.ready?.docs;\n", js, count=1)
rep("function stageOf(m){\n", "function stageOf(m){\n  if (m.pending) return {d:{deal:!!m.rate, profile:false, docs:false, sent:false, signed:false, active:false}, next:'join', n:m.rate ? 1 : 0};\n")
rep("const NEXT_LABEL = {", "const NEXT_LABEL = {join:'Invited · not joined yet',")
rep("const groups = [['all','All'],", "const groups = [['all','All'],['join','Invited · not joined'],")
js = re.sub(r"    try \{ const k = t\.dataset\.upload, data = await readImage.*?\n    catch \(x\) \{ toast\(x\.message\); \}",
            "    try { await uploadDoc(t.dataset.upload, file); }\n    catch (x) { toast(x.message); }", js, count=1, flags=re.S)
if 'uploadDoc(t.dataset.upload' not in js: sys.exit('build-live: upload handler not patched')
rep('<p class="note">Demo: data stays in this browser. Names, PAN and bank numbers are made up.</p>', '<p class="note">Private by design: each person sees only what their role allows, and every change is logged.</p>')
rep('<button data-act="reset">Reset demo data</button>', '')
rep('${can.editDeal(r) ? `<button class="btn" data-act="edit-deal"', '${can.editDeal(r) && !m.synthetic ? `<button class="btn" data-act="edit-deal"')
rep("roleOpts = Object.entries(ROLES).filter(([k]) => isOwner(r) || ['crew','vendor','hod'].includes(k))", "roleOpts = Object.entries(ROLES).filter(([k]) => !ROLES[k].owner && (isOwner(r) || ['crew','vendor','hod'].includes(k)))")
rep('<div class="docph">Sample ${label}<br>(demo placeholder)</div>', '<div class="docph">${label} saved<br>(preview not available)</div>', 2)
# the live layer starts the app itself
a = js.rstrip().rfind('\nrender();')
if a < 0: sys.exit('build-live: final render() not found')
js = js[:a] + '\n' + (root / 'src/live.js').read_text(encoding='utf-8')

html = html.replace('<title>CrewDesk Central</title>', '<title>CrewDesk</title>')
if '<script src="app.js"></script>' not in html: sys.exit('build-live: app.js tag not found')
html = html.replace('<script src="app.js"></script>', '<script src="config.js"></script>\n<script src="app.js"></script>')
(root / 'app.js').write_text('// Generated by tools/build-live.py from central/app.js and src/live.js. Edit those, then rebuild.\n' + js, encoding='utf-8')
(root / 'index.html').write_text(html, encoding='utf-8')
print('built index.html and app.js:', len(js), 'bytes of script')
